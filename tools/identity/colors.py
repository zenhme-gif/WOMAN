def rgb(h): h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def ase(groups, path):
    """Adobe Swatch Exchange: مجموعات، ولكل لون إدخال RGB، وإدخال CMYK إن وُجدت قيمته المعتمدة."""
    blocks = []
    def name_bytes(s):
        b = s.encode('utf-16-be') + b'\x00\x00'
        return struct.pack('>H', len(b) // 2) + b
    for gname, items in groups:
        nb = name_bytes(gname)
        blocks.append(struct.pack('>HI', 0xC001, len(nb)) + nb)
        for (n, tok, hx, cmyk, role, src) in items:
            r, g, b = rgb(hx)
            body = name_bytes(f'{n} {hx}') + b'RGB ' + struct.pack('>fff', r / 255, g / 255, b / 255) + struct.pack('>H', 2)
            blocks.append(struct.pack('>HI', 0x0001, len(body)) + body)
            if cmyk:
                c, m, y, k = cmyk
                body = name_bytes(f'{n} CMYK {c}.{m}.{y}.{k}') + b'CMYK' + struct.pack('>ffff', c / 100, m / 100, y / 100, k / 100) + struct.pack('>H', 2)
                blocks.append(struct.pack('>HI', 0x0001, len(body)) + body)
        blocks.append(struct.pack('>HI', 0xC002, 0))
    data = b'ASEF' + struct.pack('>HHI', 1, 0, len(blocks)) + b''.join(blocks)
    open(path, 'wb').write(data)


def as_json(groups):
    out = {}
    for gname, items in groups:
        out[gname] = [dict(name=n, token=tok, hex=hx, rgb=list(rgb(hx)), cmyk=('%d.%d.%d.%d' % cmyk if cmyk else None), role=role, source=src)
                      for (n, tok, hx, cmyk, role, src) in items]
    return out
